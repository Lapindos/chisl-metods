print("после правки копии a остался", a)
print("Вывод: срез — это view, он смотрит в тот же массив. Если обрезать данные для анализа и изменить срез, испортится исходный эксперимент.")
print("View полезен, когда нужно смотреть кусок большого массива и не тратить память на копию.")
