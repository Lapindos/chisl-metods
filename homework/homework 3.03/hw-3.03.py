import numpy as np

print("hw-3.03")

e32 = float(np.float32(0.1)) - 0.1
e64 = float(np.float64(0.1)) - 0.1
print("float32:", repr(e32), f"{e32:.20e}")
print("float64:", repr(e64), f"{e64:.20e}")
if e64 == 0:
    print("Ошибка float64 в этом сравнении равна 0, ошибка float32 нет. float32 хуже во много раз.")
else:
    print("ошибка float32 больше ошибки float64 в", abs(e32) / abs(e64), "раз")
print("Вывод: float32 хватает для картинки, грубой оценки и места, где не нужна длинная точность.")
print("Для численных методов с вычитанием близких чисел, длинными суммами и корнями нужен float64.")
print("Иначе ошибка округления съедает сам ответ, как здесь с числом 0.1.")
